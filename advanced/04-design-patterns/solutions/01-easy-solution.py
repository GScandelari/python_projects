# Exercise 3 — Template Method: Report generator
# ----------------------------------------------------------
class Report:
    def __init__(self, title):
        self.title = title

    def header(self):
        raise NotImplementedError

    def body(self):
        return f"Report content for: {self.title}"

    def footer(self):
        raise NotImplementedError

    def generate(self):
        print(self.header())
        print(self.body())
        print(self.footer())
        print()


class HTMLReport(Report):
    def header(self):
        return f"<html><body>\n<h1>{self.title}</h1>"

    def footer(self):
        return f"<footer>Generated by HTMLReport</footer>\n</body></html>"


class TextReport(Report):
    def header(self):
        sep = "=" * max(20, len(self.title) + 4)
        return f"{sep}\n{self.title}\n{sep}"

    def footer(self):
        return f"Generated by TextReport"


print("--- HTMLReport ---")
HTMLReport("Sales Q1").generate()

print("--- TextReport ---")
TextReport("Sales Q1").generate()
